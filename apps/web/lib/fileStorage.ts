import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { createClient, type SupabaseClient } from "@supabase/supabase-js";
import type { FileStore } from "@tikmi/ingest";

/**
 * Private file storage: PJP submissions (every version's original), templates
 * and exports. Production uses one private Supabase Storage bucket (the same
 * vendor as the IRA app's uploads); nothing is ever public, and files are
 * served through authenticated routes (app/api/files/...). Uploads from Apps
 * Script go straight to the bucket with one-time signed URLs, so they never
 * pass through a Vercel function and its 4.5 MB request limit.
 *
 * Without SUPABASE_URL / SUPABASE_SECRET_KEY (local development) files are kept
 * under .tikmi-files/ in the repo instead; that fallback refuses to run in
 * production, where the filesystem is not persistent.
 */
export const BUCKET = process.env.TIKMI_STORAGE_BUCKET ?? "tikmi-files";
const MAX_FILE_BYTES = 50 * 1024 * 1024;
/** Keys are generated by the app (packages/ingest), so a client can only point at an object it was given. */
const KEY = /^(submissions|templates|exports|sumber-bi)\/[\w./-]+\.xlsx$/;

let client: SupabaseClient | null | undefined;
function supabase(): SupabaseClient | null {
  if (client === undefined) {
    const url = process.env.SUPABASE_URL;
    const key = process.env.SUPABASE_SECRET_KEY;
    client = url && key ? createClient(url, key, { auth: { persistSession: false, autoRefreshToken: false } }) : null;
  }
  return client;
}

export function storageEnabled(): boolean {
  return supabase() !== null;
}

export function isStorageKey(key: unknown): key is string {
  return typeof key === "string" && KEY.test(key) && !key.includes("..");
}

let bucketReady: Promise<void> | null = null;
/** Creates the private bucket on first use, so a new Supabase project needs no manual setup. */
function ensureBucket(storage: SupabaseClient["storage"]): Promise<void> {
  bucketReady ??= (async () => {
    const { error } = await storage.getBucket(BUCKET);
    if (!error) return;
    const created = await storage.createBucket(BUCKET, { public: false, fileSizeLimit: MAX_FILE_BYTES });
    if (created.error && !/already exists/i.test(created.error.message)) throw created.error;
  })().catch((err) => {
    bucketReady = null;
    throw err;
  });
  return bucketReady;
}

const LOCAL_DIR = resolve(process.cwd(), process.env.TIKMI_LOCAL_FILES ?? "../../.tikmi-files");

function localPath(key: string) {
  if (process.env.NODE_ENV === "production") throw new Error("File storage is not configured (SUPABASE_URL / SUPABASE_SECRET_KEY)");
  if (!isStorageKey(key)) throw new Error(`Invalid storage key ${key}`);
  return resolve(LOCAL_DIR, key);
}

export const fileStore: FileStore = {
  async put(key, bytes, contentType) {
    const sb = supabase();
    if (!sb) {
      const p = localPath(key);
      await mkdir(dirname(p), { recursive: true });
      await writeFile(p, bytes);
      return;
    }
    await ensureBucket(sb.storage);
    const { error } = await sb.storage.from(BUCKET).upload(key, bytes, { contentType, upsert: false });
    if (error) throw error;
  },
  async get(key) {
    const sb = supabase();
    if (!sb) {
      try {
        return await readFile(localPath(key));
      } catch {
        return null;
      }
    }
    const { data, error } = await sb.storage.from(BUCKET).download(key);
    if (error || !data) return null;
    return Buffer.from(await data.arrayBuffer());
  },
};

/** One-time URL a client PUTs the file to (valid 2 hours). Null without Supabase: the client posts the file to the app instead. */
export async function signedUploadUrl(key: string): Promise<{ url: string; token: string } | null> {
  const sb = supabase();
  if (!sb) return null;
  if (!isStorageKey(key)) throw new Error(`Invalid storage key ${key}`);
  await ensureBucket(sb.storage);
  const { data, error } = await sb.storage.from(BUCKET).createSignedUploadUrl(key);
  if (error) throw error;
  return { url: data.signedUrl, token: data.token };
}
